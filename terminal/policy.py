"""Structured, allowlisted operation plans without shell execution."""

from __future__ import annotations

import hashlib
import json
import math
import re
import unicodedata
from collections.abc import Callable, Mapping
from dataclasses import dataclass
from enum import IntEnum
from typing import Any


MAX_ARGUMENTS_BYTES = 8_192
MAX_ARGUMENT_DEPTH = 12
MAX_ARGUMENT_NODES = 512
_OPERATION_ID = re.compile(r"[a-z][a-z0-9_.-]{0,63}\Z")


class TerminalPolicyError(ValueError):
    """Raised when a proposed operation is not allowed by local policy."""


class RiskTier(IntEnum):
    READ_ONLY = 1
    MODIFICATION = 2
    HIGH_RISK = 3


def _safe_display_text(value: str, field: str, maximum: int) -> str:
    if not isinstance(value, str) or not value.strip():
        raise TerminalPolicyError(f"Preview {field} must be non-empty text.")
    escaped = "".join(
        f"\\u{ord(character):04x}"
        if unicodedata.category(character) in {"Cc", "Cf", "Cs"}
        else character
        for character in value.strip()
    )
    if len(escaped) > maximum:
        raise TerminalPolicyError(f"Preview {field} exceeds its display limit.")
    return escaped


def _validate_json_value(value: Any, *, depth: int, nodes: list[int]) -> None:
    nodes[0] += 1
    if nodes[0] > MAX_ARGUMENT_NODES or depth > MAX_ARGUMENT_DEPTH:
        raise TerminalPolicyError("Operation arguments are too complex.")

    value_type = type(value)
    if value is None or value_type in (str, bool, int):
        return
    if value_type is float:
        if not math.isfinite(value):
            raise TerminalPolicyError("Operation arguments must use finite numbers.")
        return
    if value_type is list:
        for item in value:
            _validate_json_value(item, depth=depth + 1, nodes=nodes)
        return
    if value_type is dict:
        for key, item in value.items():
            if not isinstance(key, str):
                raise TerminalPolicyError("Operation argument keys must be strings.")
            _validate_json_value(item, depth=depth + 1, nodes=nodes)
        return
    raise TerminalPolicyError("Operation arguments must contain JSON values only.")


@dataclass(frozen=True, slots=True)
class ChangePreview:
    """Human-readable impact generated by trusted application code."""

    title: str
    description: str
    affected_resources: tuple[str, ...] = ()

    def __post_init__(self) -> None:
        object.__setattr__(self, "title", _safe_display_text(self.title, "title", 120))
        object.__setattr__(
            self,
            "description",
            _safe_display_text(self.description, "description", 1_000),
        )
        if not isinstance(self.affected_resources, (tuple, list)):
            raise TerminalPolicyError("Preview resources must be a list or tuple.")
        try:
            resources = tuple(self.affected_resources)
        except TypeError as exc:
            raise TerminalPolicyError("Preview resources must be a sequence.") from exc
        if len(resources) > 32:
            raise TerminalPolicyError("Preview has too many affected resources.")
        resources = tuple(
            _safe_display_text(item, "resource", 512) for item in resources
        )
        object.__setattr__(self, "affected_resources", resources)


ArgumentValidator = Callable[[Mapping[str, Any]], None]
PreviewBuilder = Callable[[Mapping[str, Any]], ChangePreview]


@dataclass(frozen=True, slots=True)
class OperationDefinition:
    """Trusted, static policy for one structured operation identifier.

    `risk_tier`, argument validation, and preview generation are owned by the
    application. A model proposal cannot supply or override them. Validation
    and preview callbacks must be deterministic and must not perform side effects.
    """

    operation_id: str
    risk_tier: RiskTier
    validate_arguments: ArgumentValidator
    build_preview: PreviewBuilder

    def __post_init__(self) -> None:
        if not isinstance(self.operation_id, str) or not _OPERATION_ID.fullmatch(
            self.operation_id
        ):
            raise TerminalPolicyError("Operation IDs must be short lowercase identifiers.")
        try:
            object.__setattr__(self, "risk_tier", RiskTier(self.risk_tier))
        except (TypeError, ValueError) as exc:
            raise TerminalPolicyError("Operation has an invalid risk tier.") from exc
        if not callable(self.validate_arguments) or not callable(self.build_preview):
            raise TerminalPolicyError("Operation policies need validators and previews.")


@dataclass(frozen=True, slots=True)
class OperationPlan:
    """Validated operation plus a stable fingerprint for approval binding."""

    operation_id: str
    risk_tier: RiskTier
    arguments_json: str
    preview: ChangePreview
    fingerprint: str

    @property
    def arguments(self) -> dict[str, Any]:
        """Return a detached copy; callers cannot mutate the approved plan."""
        return json.loads(self.arguments_json)


class OperationRegistry:
    """Resolve proposals through trusted operation definitions only."""

    def __init__(self, definitions: tuple[OperationDefinition, ...] = ()) -> None:
        self._definitions: dict[str, OperationDefinition] = {}
        for definition in definitions:
            if definition.operation_id in self._definitions:
                raise TerminalPolicyError(
                    f"Duplicate terminal operation: {definition.operation_id}."
                )
            self._definitions[definition.operation_id] = definition

    def plan(
        self,
        operation_id: str,
        arguments: Mapping[str, Any],
    ) -> OperationPlan:
        if not isinstance(operation_id, str) or not _OPERATION_ID.fullmatch(
            operation_id
        ):
            raise TerminalPolicyError("Operation ID is invalid.")
        definition = self._definitions.get(operation_id)
        if definition is None:
            raise TerminalPolicyError("Terminal operation is not allowlisted.")
        if definition.risk_tier is RiskTier.HIGH_RISK:
            raise TerminalPolicyError("Tier 3 operations are denied by default.")
        if not isinstance(arguments, Mapping):
            raise TerminalPolicyError("Operation arguments must be an object.")

        detached_arguments = dict(arguments)
        if any(not isinstance(key, str) for key in detached_arguments):
            raise TerminalPolicyError("Operation argument keys must be strings.")
        _validate_json_value(detached_arguments, depth=0, nodes=[0])
        try:
            serialized_arguments = json.dumps(
                detached_arguments,
                ensure_ascii=False,
                sort_keys=True,
                separators=(",", ":"),
                allow_nan=False,
            )
        except (TypeError, ValueError) as exc:
            raise TerminalPolicyError("Operation arguments must be JSON values.") from exc
        try:
            arguments_size = len(serialized_arguments.encode("utf-8"))
        except UnicodeEncodeError as exc:
            raise TerminalPolicyError("Operation arguments contain invalid text.") from exc
        if arguments_size > MAX_ARGUMENTS_BYTES:
            raise TerminalPolicyError("Operation arguments exceed the size limit.")

        validated_arguments = json.loads(serialized_arguments)
        definition.validate_arguments(validated_arguments)
        preview = definition.build_preview(json.loads(serialized_arguments))
        if not isinstance(preview, ChangePreview):
            raise TerminalPolicyError("Operation preview must use ChangePreview.")

        fingerprint_payload = json.dumps(
            {
                "operation_id": definition.operation_id,
                "risk_tier": int(definition.risk_tier),
                "arguments": serialized_arguments,
                "preview": {
                    "title": preview.title,
                    "description": preview.description,
                    "affected_resources": preview.affected_resources,
                },
            },
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
        ).encode("utf-8")
        fingerprint = hashlib.sha256(fingerprint_payload).hexdigest()

        return OperationPlan(
            operation_id=definition.operation_id,
            risk_tier=definition.risk_tier,
            arguments_json=serialized_arguments,
            preview=preview,
            fingerprint=fingerprint,
        )

    def tier_for(self, operation_id: str) -> RiskTier:
        if not isinstance(operation_id, str) or not _OPERATION_ID.fullmatch(
            operation_id
        ):
            raise TerminalPolicyError("Operation ID is invalid.")
        definition = self._definitions.get(operation_id)
        if definition is None:
            raise TerminalPolicyError("Terminal operation is not allowlisted.")
        return definition.risk_tier
